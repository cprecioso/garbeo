// Bundles the plugin host page into App/PaseoSwift/PluginHost/plugin-host.js.
//
// The Paseo SDK packages (@getpaseo/plugin, @getpaseo/client and their protocol/relay deps) are
// compiled from an upstream checkout rather than npm, so the host matches the daemon's version
// exactly: PASEO_SRC=/path/to/getpaseo/paseo (default /tmp/paseo-src/paseo), at PASEO_REF.
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const PASEO_REF = "0009a7e"; // getpaseo/paseo v0.11.1
const here = path.dirname(fileURLToPath(import.meta.url));
const paseo = path.resolve(process.env.PASEO_SRC ?? "/tmp/paseo-src/paseo");
const packages = path.join(paseo, "packages");
if (!existsSync(packages)) {
  console.error(`Paseo source not found at ${paseo}. Clone github.com/getpaseo/paseo and set PASEO_SRC.`);
  process.exit(1);
}
const head = execFileSync("git", ["-C", paseo, "rev-parse", "--short=7", "HEAD"]).toString().trim();
if (head !== PASEO_REF) console.warn(`warning: ${paseo} is at ${head}, expected ${PASEO_REF}`);

const exact = {
  "@getpaseo/plugin": "plugin/src/index.ts",
  "@getpaseo/plugin/client": "plugin/src/client/index.ts",
  "@getpaseo/plugin/client/host": "plugin/src/client/host.ts",
  "@getpaseo/client": "client/src/index.ts",
  "@getpaseo/client/internal/daemon-client": "client/src/daemon-client.ts",
  "@getpaseo/client/internal/daemon-client-transport-types": "client/src/daemon-client-transport-types.ts",
  "@getpaseo/relay": "relay/src/index.ts",
  "@getpaseo/relay/e2ee": "relay/src/e2ee.ts",
};

// Node-only modules reachable from the client SDK (desktop transports, the `ws` fallback) are
// never called in the page; resolve them to empty modules.
const nodeOnly = /^(node:.*|ws|fs|path|net|os|crypto|child_process|stream|util|events|url|http|https|tls|zlib|buffer)$/;

const sdkSources = {
  name: "paseo-sdk-sources",
  setup(build) {
    build.onResolve({ filter: /^@getpaseo\// }, (args) => {
      if (exact[args.path]) return { path: path.join(packages, exact[args.path]) };
      const protocol = args.path.match(/^@getpaseo\/protocol\/(.+)$/);
      if (protocol) return { path: path.join(packages, "protocol/src", `${protocol[1]}.ts`) };
      return { errors: [{ text: `No source mapping for ${args.path}` }] };
    });
    // The protocol package ships a zod-aot compiled validator generated at build time. The plain
    // zod schema it is compiled from validates the same messages, just slower.
    build.onResolve({ filter: /generated\/validation\/ws-outbound\.aot\.js$/ }, () => ({
      path: "ws-outbound-aot",
      namespace: "aot-shim",
    }));
    build.onLoad({ filter: /.*/, namespace: "aot-shim" }, () => ({
      contents: `export { WSOutboundMessageSchema } from ${JSON.stringify(path.join(packages, "protocol/src/messages.ts"))};`,
      loader: "js",
      resolveDir: path.join(packages, "protocol/src"),
    }));
    build.onResolve({ filter: nodeOnly }, (args) => ({ path: args.path, namespace: "node-stub" }));
    build.onLoad({ filter: /.*/, namespace: "node-stub" }, () => ({ contents: "module.exports = {};", loader: "js" }));
  },
};

await esbuild.build({
  entryPoints: [path.join(here, "src/main.tsx")],
  outfile: path.join(here, "../App/PaseoSwift/PluginHost/plugin-host.js"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["safari17"],
  jsx: "automatic",
  minify: true,
  legalComments: "none",
  nodePaths: [path.join(here, "node_modules")],
  alias: { "react-native": "react-native-web" },
  define: { "process.env.NODE_ENV": '"production"', global: "globalThis" },
  plugins: [sdkSources],
  banner: { js: `/* Paseo Swift plugin host. Generated by PluginHost/build.mjs from getpaseo/paseo@${head}. Do not edit. */` },
  logLevel: "info",
});
